// ============= CSV PARSING =============
const parseCSV = (csvText: string): DataRow[] => {
  const lines = csvText.trim().split('\n');
  const headers = lines[0].split(/[,;]/).map(h => h.trim());
  
  return lines.slice(1).map(line => {
    const values = line.split(/[,;]/).map(v => v.trim());
    const row: any = {};
    
    headers.forEach((header, i) => {
      const value = values[i];
      if (header === 'date') {
        // Parse DD/MM/YYYY format
        const parts = value.split('/');
        if (parts.length === 3) {
          const day = parts[0];
          const month = parts[1];
          const year = parts[2];
          row.date = new Date(`${year}-${month}-${day}`);
          row.dateStr = value;
          row.year = parseInt(year);
          row.month = parseInt(month);
        } else {
          row.date = new Date(value);
          row.dateStr = value;
          row.year = row.date.getFullYear();
          row.month = row.date.getMonth() + 1;
        }
      } else {
        row[header] = value === '' ? 0 : parseFloat(value) || 0;
      }
    });
    
    // Compute derived metrics
    row.net_sales_gbp = row.gross_sales_gbp - row.discounts_gbp - row.refunds_gbp;
    row.contribMarginPct = row.net_sales_gbp > 0
      ? ((row.net_sales_gbp - row.transaction_fees_gbp - row.marketing_spend_total_gbp) / row.net_sales_gbp) * 100
      : 0;
    row.blendedCAC = row.new_customers > 0 ? row.marketing_spend_total_gbp / row.new_customers : 0;
    
    const repeatRate = row.orders > 0 ? row.returning_customers / row.orders : 0.5;
    row.paybackPeriod = (row.aov_gbp * 0.95 * repeatRate) > 0
      ? row.blendedCAC / (row.aov_gbp * 0.95 * repeatRate)
      : 0;
    
    row.discountRate = row.gross_sales_gbp > 0 ? (row.discounts_gbp / row.gross_sales_gbp) * 100 : 0;
    row.refundRate = row.gross_sales_gbp > 0 ? (row.refunds_gbp / row.gross_sales_gbp) * 100 : 0;
    
    return row as DataRow;
  });
};

