const getGARColor = (value: number, thresholds: any): string => {
  if (!thresholds) return COLORS.amber;
  const { green, amber, red, invert } = thresholds;
  if (invert) {
    if (value <= green) return COLORS.green;
    if (value <= amber) return COLORS.amber;
    return COLORS.red;
  } else {
    if (value >= green) return COLORS.green;
    if (value >= amber) return COLORS.amber;
    if (red !== undefined && value >= red) return COLORS.red;
    return COLORS.red;
  }
};

const calculateDelta = (current: number, previous: number): number => {
  if (!previous) return 0;
  return ((current - previous) / previous) * 100;
};

const calculatePearson = (x: number[], y: number[]): number => {
  const n = x.length;
  if (n === 0) return 0;
  
  const sumX = x.reduce((a, b) => a + b, 0);
  const sumY = y.reduce((a, b) => a + b, 0);
  const sumXY = x.reduce((sum, xi, i) => sum + xi * y[i], 0);
  const sumX2 = x.reduce((sum, xi) => sum + xi * xi, 0);
  const sumY2 = y.reduce((sum, yi) => sum + yi * yi, 0);
  
  const numerator = n * sumXY - sumX * sumY;
  const denominator = Math.sqrt((n * sumX2 - sumX * sumX) * (n * sumY2 - sumY * sumY));
  
  return denominator === 0 ? 0 : numerator / denominator;
};

